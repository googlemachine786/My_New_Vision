@dataclass
class FeedbackEvent:
    """Feedback event from ai_feedback_loop table."""
    feedback_id: str
    session_id: str
    user_query: str
    retrieved_context: List[str]  # UUIDs
    llm_response: str
    feedback_score: int  # -1, 0, 1
    created_at: datetime


@dataclass
class GoldenResponse:
    """Golden response generated by LLM Judge."""
    feedback_id: str
    golden_response: str
    confidence: float
    reasoning: str


class LLMJudge:
    """LLM Judge for evaluating negative feedback."""
    
    def __init__(self, project_id: str, location: str, model: str = "gemini-2.0-flash"):
        self.project_id = project_id
        self.location = location
        self.model = model
        
        # Initialize Vertex AI
        aiplatform.init(project=project_id, location=location)
        
        self.client = aiplatform.TextGenerationModel.from_pretrained(model)
    
    async def judge_feedback(
        self,
        feedback: FeedbackEvent,
        context_chunks: List[Dict[str, str]],
    ) -> Optional[GoldenResponse]:
        """
        Judge negative feedback and generate golden response.
        
        Args:
            feedback: Feedback event
            context_chunks: Retrieved context chunks (content from UUIDs)
        
        Returns:
            GoldenResponse if successful, None otherwise
        """
        if not context_chunks:
            return None
        
        # Build prompt for LLM Judge
        prompt = self._build_judge_prompt(feedback, context_chunks)
        
        try:
            # Call Gemini 2.0 Flash
            response = await self._generate_with_gemini(prompt)
            
            # Parse response
            golden_response, confidence, reasoning = self._parse_judge_response(response)
            
            return GoldenResponse(
                feedback_id=feedback.feedback_id,
                golden_response=golden_response,
                confidence=confidence,
                reasoning=reasoning,
            )
            
        except Exception as e:
            print(f"Judge failed: {e}")
            return None
    
    def _build_judge_prompt(
        self,
        feedback: FeedbackEvent,
        context_chunks: List[Dict[str, str]],
    ) -> str:
        """Build prompt for LLM Judge."""
        context_text = "\n\n".join([
            f"[Source {i+1} | Page {chunk.get('page', '?')}]\n{chunk['content']}"
            for i, chunk in enumerate(context_chunks)
        ])
        
        prompt = f"""You are a CBSE science education expert for Indian students (Grades 6-8).

Using ONLY the following retrieved context, write a correct, complete, grade-appropriate answer.
Do not add information outside the context.

Retrieved Context:
{context_text}

Student Query: {feedback.user_query}

Rejected Response (do NOT repeat this): {feedback.llm_response}

Task:
1. Evaluate if the rejected response is incorrect, incomplete, or misleading based on the context.
2. Write a corrected, pedagogically sound response using only the provided context.
3. Cite page numbers and sections.

Format:
- First line: Confidence score (0.0-1.0)
- Second line: Brief reasoning
- Rest: Corrected response

Example:
0.95
The original response missed the key point about chlorophyll and didn't mention the reactants.
Photosynthesis is the process by which green plants make food using sunlight, water, and carbon dioxide. The process requires chlorophyll, a green pigment in chloroplasts, to capture light energy. [Page 42, Section: Photosynthesis Process]
"""
        
        return prompt
    
    async def _generate_with_gemini(self, prompt: str) -> str:
        """Generate response with Gemini."""
        loop = asyncio.get_event_loop()
        
        def generate():
            with telemetry.tool_context_manager("visionary-quality-loop"):
                response = self.client.predict(
                    prompt,
                    temperature=0.1,
                    max_output_tokens=512,
                )
                return response.text
        
        return await loop.run_in_executor(None, generate)
    
    def _parse_judge_response(self, response: str) -> tuple:
        """Parse LLM Judge response."""
        lines = response.strip().split('\n')
        
        # Parse confidence
        try:
            confidence = float(lines[0].strip())
        except (ValueError, IndexError):
            confidence = 0.5
        
        # Parse reasoning
        try:
            reasoning = lines[1].strip()
        except IndexError:
            reasoning = "No reasoning provided"
        
        # Golden response is everything after first two lines
        golden_response = '\n'.join(lines[2:]).strip() if len(lines) > 2 else response
        
        return golden_response, confidence, reasoning


async def process_feedback_batch(
    feedback_events: List[FeedbackEvent],
    db_connection,
    judge: LLMJudge,
    batch_size: int = 10,
) -> Dict[str, int]:
    """
    Process batch of negative feedback events.
    
    Args:
        feedback_events: List of feedback events
        db_connection: Database connection for fetching chunks
        judge: LLM Judge instance
        batch_size: Batch size for processing
    
    Returns:
        Dict with success/failure counts
    """
    success_count = 0
    failure_count = 0
    
    for i in range(0, len(feedback_events), batch_size):
        batch = feedback_events[i:i + batch_size]
        
        # Process batch concurrently
        tasks = []
        for feedback in batch:
            # Fetch context chunks using UUIDs
            context_chunks = await fetch_context_chunks(
                db_connection,
                feedback.retrieved_context,
            )
            
            if not context_chunks:
                print(f"Skipping {feedback.feedback_id}: No context chunks found")
                failure_count += 1
                continue
            
            task = judge.judge_feedback(feedback, context_chunks)
            tasks.append(task)
        
        # Wait for batch
        results = await asyncio.gather(*tasks, return_exceptions=True)
        
        # Process results
        for feedback, result in zip(batch, results):
            if isinstance(result, Exception):
                print(f"Error processing {feedback.feedback_id}: {result}")
                failure_count += 1
                continue
            
            if result is None:
                failure_count += 1
                continue
            
            # Update database with golden response
            await update_feedback_with_golden(
                db_connection,
                feedback.feedback_id,
                result.golden_response,
                result.confidence,
            )
            
            success_count += 1
            print(f"✓ Processed {feedback.feedback_id}")
    
    return {
        'success': success_count,
        'failure': failure_count,
        'total': len(feedback_events),
    }


